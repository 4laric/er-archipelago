def _wizard_surface() -> set[str]:
    """Player-facing options, from the generated wizard metadata. Regenerated by
    tools/dump_options_metadata.py, so it cannot drift from the option classes without a red."""
    try:
        import json
        with open(_METADATA, "r", encoding="utf-8") as f:
            md = json.load(f)
    except Exception:
        return set()
    keys = set(md.get("field_order") or ())
    for g in md.get("groups") or ():
        for o in (g.get("options") or g.get("fields") or ()):
            keys.add(o if isinstance(o, str) else o.get("name"))
    keys.update(o if isinstance(o, str) else o.get("name") for o in (md.get("ungrouped") or ()))
    return {k for k in keys if k}


def _frozen_keys() -> set[str]:
    """defaults.FROZEN_OPTIONS -- off the wizard surface but VALID in a yaml. AP silently drops
    them, so naming one is stale rather than wrong and must not be reported as unknown.

    Loaded by file path, not by import: this script has to stay AP-free so it can run in the fast
    CI job, and `greenfield.eldenring.defaults` is a leaf module with no Archipelago import."""
    try:
        import importlib.util
        spec = importlib.util.spec_from_file_location("_gf_defaults", _DEFAULTS)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        return set(getattr(mod, "FROZEN_OPTIONS", {}) or ())
    except Exception:
        return set()


def load_valid_keys() -> set[str]:
    """Every key a yaml may name without being wrong. Empty -> the unknown-key rule SKIPS, so the
    two loaders above failing open is a deliberate soft landing rather than a wall of false errors.

    🛑 An empty return means rule 0 is OFF, and it was off, silently, for the whole life of this
    file -- both paths it used to look for stopped existing at the greenfield port, `EROptions` was
    replaced by `GFOptions`, and the `if VALID_KEYS:` guard below turned that into silence rather
    than a failure. `--self-check` exists so that cannot recur unnoticed."""
    surface = _wizard_surface()
    if not surface:
        return set()
    return surface | _frozen_keys() | _COMMON_KEYS

