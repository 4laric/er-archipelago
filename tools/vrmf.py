#!/usr/bin/env python3
"""vrmf.py -- the four-part release version, V.R.M.F, and the three spellings it takes.

THE RULE (Alaric, 2026-09-06): a client is compatible with every seed generated by an apworld on
the same V.R.M. The bar for a fixpack (F) is exactly "can I swap to the v0.6.0.1 client on a seed
that was generated with the v0.6.0 apworld" -- either side may change in a fixpack so long as that
holds. The contract hash MAY move on a fixpack when the new client bridges the older contract (the
audited-compatible path in the client's core.rs); it is the swap that must hold, not the hash.

WHY THREE SPELLINGS, and why this file exists to hold them in one place:

  * `0.6.0.1`   -- the RELEASE version. contract.py APWORLD_VERSION, the seed's `versions` string
                   (`apworld/0.6.0.1`), the wizard's apworld_version, changelog headings, blurb
                   file names, ledger rows, release tags. Four parts; `.0` is spelled out only when
                   a fixpack has been cut on that line (the first release on a line is `0.6.0`).
  * `0.6.0`     -- the MANIFEST version. Archipelago's `Utils.tuplize_version` unpacks
                   archipelago.json `world_version` into a THREE-field NamedTuple, so a fourth
                   part is a TypeError at apworld load. The manifest carries V.R.M only.
  * `0.6.0+f1`  -- the CARGO version. Cargo requires a semver core, so the client crate carries F
                   as build metadata (`+f<F>`), which er-semver strips when it compares cores.
                   F=0 is a bare `0.6.0`.

AP-free and import-free on purpose: the version gates run in the cheap CI job and on boxes with
no Archipelago checkout. Every gate that reads a version site goes through `canonical()` so the
three spellings compare as one number.
"""
import re

VRMF = re.compile(r"^(\d+)\.(\d+)\.(\d+)(?:\.(\d+))?$")
CARGO = re.compile(r"^(\d+)\.(\d+)\.(\d+)(?:\+f(\d+))?$")


def parse(version):
    """'0.6.0.1' | '0.6.0' | '0.6.0+f1' -> (major, minor, patch, fixpack). ValueError otherwise."""
    s = str(version).strip()
    m = VRMF.match(s) or CARGO.match(s)
    if not m:
        raise ValueError("not a V.R.M[.F] / V.R.M[+fF] version: %r" % (version,))
    return tuple(int(m.group(i) or 0) for i in range(1, 5))


def is_version(version):
    try:
        parse(version)
    except ValueError:
        return False
    return True


def canonical(version):
    """The release spelling: '0.6.0' when F is 0, '0.6.0.1' otherwise."""
    v, r, m, f = parse(version)
    return "%d.%d.%d" % (v, r, m) if f == 0 else "%d.%d.%d.%d" % (v, r, m, f)


def vrm(version):
    """The seed-compatibility line -- what archipelago.json carries and what a client must share."""
    v, r, m, _f = parse(version)
    return "%d.%d.%d" % (v, r, m)


def fixpack(version):
    return parse(version)[3]


def cargo(version):
    """The client crate spelling: '0.6.0' or '0.6.0+f1'."""
    v, r, m, f = parse(version)
    return "%d.%d.%d" % (v, r, m) if f == 0 else "%d.%d.%d+f%d" % (v, r, m, f)


# The spelling each version SITE holds. Anything not listed holds the canonical release version.
SITE_FORM = {
    "manifest": vrm,      # archipelago.json world_version
    "cargo": cargo,       # client Cargo.toml / Cargo.lock
}


def site_value(version, form=None):
    """What a site of the given form should read for `version`."""
    return SITE_FORM.get(form, canonical)(version)


def agrees(site_read, version, form=None):
    """Whether a site's raw reading spells `version` in that site's form."""
    try:
        return site_value(site_read, form) == site_value(version, form) and (
            form in SITE_FORM or canonical(site_read) == canonical(version))
    except ValueError:
        return False


def sequence_error(current, target):
    """Why `target` may not follow `current`, or None.

    A fixpack advances F by exactly one on the same V.R.M. A new V.R.M resets F to 0 and, within a
    minor line, advances the patch by exactly one; minor/major windows are left to judgement."""
    old, new = parse(current), parse(target)
    if new <= old:
        return "%s does not advance %s" % (target, current)
    if new[:3] == old[:3]:
        if new[3] != old[3] + 1:
            return ("fixpacks advance by exactly one: %s -> %s, not %s"
                    % (current, canonical("%d.%d.%d.%d" % (old[0], old[1], old[2], old[3] + 1)),
                       target))
        return None
    if new[3] != 0:
        return "a new V.R.M starts at fixpack 0: %s, not %s" % (vrm(target), target)
    if new[:2] == old[:2] and new[2] != old[2] + 1:
        return ("patch windows must advance by exactly one: %s -> %d.%d.%d, not %s"
                % (current, old[0], old[1], old[2] + 1, target))
    return None


if __name__ == "__main__":
    import sys
    for arg in sys.argv[1:]:
        print(arg, "->", canonical(arg), vrm(arg), cargo(arg), "F=%d" % fixpack(arg))
